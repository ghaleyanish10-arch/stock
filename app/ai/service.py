@dataclass
class AISettings:
    """AI provider settings from environment variables."""
    provider: str  # "openai", "anthropic", "ollama", "fake"
    model: str
    api_key: Optional[str] = None
    base_url: Optional[str] = None
    temperature: float = 0.1
    max_tokens: int = 2000
    timeout_seconds: int = 30


def get_ai_settings() -> AISettings:
    """Read AI configuration from environment variables."""
    provider = os.getenv("LLM_PROVIDER", "fake").lower()
    model = os.getenv("LLM_MODEL", "gpt-4o-mini")
    api_key = os.getenv("LLM_API_KEY")
    base_url = os.getenv("LLM_BASE_URL")
    temperature = float(os.getenv("LLM_TEMPERATURE", "0.1"))
    max_tokens = int(os.getenv("LLM_MAX_TOKENS", "2000"))
    timeout_seconds = int(os.getenv("LLM_TIMEOUT_SECONDS", "30"))

    return AISettings(
        provider=provider,
        model=model,
        api_key=api_key,
        base_url=base_url,
        temperature=temperature,
        max_tokens=max_tokens,
        timeout_seconds=timeout_seconds,
    )


class AIClient(ABC):
    """Abstract AI client interface."""

    @abstractmethod
    async def chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        """Send a chat completion request."""
        pass

    @abstractmethod
    async def stream_chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        """Stream a chat completion."""
        pass


class FakeAIClient(AIClient):
    """Deterministic fake AI client for tests and when no provider configured."""

    def __init__(self, delay_ms: int = 50):
        self._delay = delay_ms / 1000.0

    async def chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        await asyncio.sleep(self._delay)
        user_msg = messages[-1].get("content", "") if messages else ""
        return (
            "[AI not configured — this is a fake response]\n\n"
            f"You asked: {user_msg[:200]}\n\n"
            "This response is generated by the fake AI client because "
            "no LLM provider is configured (set LLM_PROVIDER and LLM_API_KEY). "
            "In production, this would be a grounded answer citing NEPSE data sources."
        )

    async def stream_chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        response = await self.chat(messages, system_prompt=system_prompt, temperature=temperature, max_tokens=max_tokens)
        for chunk in response.split(" "):
            yield chunk + " "
            await asyncio.sleep(0.01)


class OpenAIClient(AIClient):
    """OpenAI-compatible client (works with OpenAI, Azure, Ollama, etc.)."""

    def __init__(self, settings: AISettings):
        self._settings = settings
        self._client = None
        self._init_client()

    def _init_client(self):
        try:
            import openai
            self._client = openai.AsyncOpenAI(
                api_key=self._settings.api_key,
                base_url=self._settings.base_url,
                timeout=self._settings.timeout_seconds,
            )
        except ImportError:
            raise RuntimeError("openai package not installed. Run: pip install openai")

    async def chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        msgs = []
        if system_prompt:
            msgs.append({"role": "system", "content": system_prompt})
        msgs.extend(messages)

        resp = await self._client.chat.completions.create(
            model=self._settings.model,
            messages=msgs,
            temperature=temperature if temperature is not None else self._settings.temperature,
            max_tokens=max_tokens or self._settings.max_tokens,
        )
        return resp.choices[0].message.content or ""

    async def stream_chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        msgs = []
        if system_prompt:
            msgs.append({"role": "system", "content": system_prompt})
        msgs.extend(messages)

        stream = await self._client.chat.completions.create(
            model=self._settings.model,
            messages=msgs,
            temperature=temperature if temperature is not None else self._settings.temperature,
            max_tokens=max_tokens or self._settings.max_tokens,
            stream=True,
        )
        async for chunk in stream:
            if chunk.choices and chunk.choices[0].delta.content:
                yield chunk.choices[0].delta.content


class AnthropicClient(AIClient):
    """Anthropic Claude client."""

    def __init__(self, settings: AISettings):
        self._settings = settings
        self._client = None
        self._init_client()

    def _init_client(self):
        try:
            import anthropic
            self._client = anthropic.AsyncAnthropic(
                api_key=self._settings.api_key,
                base_url=self._settings.base_url,
                timeout=self._settings.timeout_seconds,
            )
        except ImportError:
            raise RuntimeError("anthropic package not installed. Run: pip install anthropic")

    async def chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        msgs = [{"role": m["role"], "content": m["content"]} for m in messages]

        resp = await self._client.messages.create(
            model=self._settings.model,
            system=system_prompt or "",
            messages=msgs,
            temperature=temperature if temperature is not None else self._settings.temperature,
            max_tokens=max_tokens or self._settings.max_tokens,
        )
        return "".join(block.text for block in resp.content if block.type == "text")

    async def stream_chat(
        self,
        messages: list[dict[str, str]],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        msgs = [{"role": m["role"], "content": m["content"]} for m in messages]

        stream = await self._client.messages.create(
            model=self._settings.model,
            system=system_prompt or "",
            messages=msgs,
            temperature=temperature if temperature is not None else self._settings.temperature,
            max_tokens=max_tokens or self._settings.max_tokens,
            stream=True,
        )
        async for event in stream:
            if event.type == "content_block_delta" and event.delta.text:
                yield event.delta.text


def create_ai_client(ai_settings: Optional[AISettings] = None) -> AIClient:
    """Factory to create the appropriate AI client based on configuration."""
    if ai_settings is None:
        ai_settings = get_ai_settings()

    if ai_settings.provider == "fake" or not ai_settings.api_key:
        return FakeAIClient()

    if ai_settings.provider in ("openai", "azure", "ollama", "openrouter"):
        return OpenAIClient(ai_settings)

    if ai_settings.provider == "anthropic":
        return AnthropicClient(ai_settings)

    raise ValueError(f"Unknown AI provider: {ai_settings.provider}")


