@dataclass
class GroundingContext:
    """Context for grounding AI answers in local data."""
    symbols: list[str]
    data_sources: list[str]  # e.g., "live_market", "archive", "corporate_actions", "news"
    cutoff_date: Optional[str] = None  # ISO date string


class RateLimiter:
    """Simple token-bucket rate limiter per user."""

    def __init__(self, max_requests: int = 20, window_seconds: int = 60):
        self.max_requests = max_requests
        self.window_seconds = window_seconds
        self._buckets: dict[str, list[float]] = {}

    def allow(self, user_id: str) -> bool:
        now = time.time()
        cutoff = now - self.window_seconds
        if user_id not in self._buckets:
            self._buckets[user_id] = []
        # Prune old entries
        self._buckets[user_id] = [ts for ts in self._buckets[user_id] if ts > cutoff]
        if len(self._buckets[user_id]) >= self.max_requests:
            return False
        self._buckets[user_id].append(now)
        return True


class AIService:
    """High-level AI service with grounding, privacy, and rate limiting."""

    def __init__(
        self,
        client: Optional[AIClient] = None,
        rate_limiter: Optional[RateLimiter] = None,
        daily_limit: int = 50,
    ):
        self._client = client or create_ai_client()
        self._rate_limiter = rate_limiter or RateLimiter(max_requests=20, window_seconds=60)
        self._daily_limit = daily_limit
        self._daily_counts: dict[str, tuple[str, int]] = {}  # user_id -> (date, count)

    def _check_daily_limit(self, user_id: str) -> bool:
        today = datetime.utcnow().date().isoformat()
        if user_id not in self._daily_counts:
            self._daily_counts[user_id] = (today, 0)
        stored_date, count = self._daily_counts[user_id]
        if stored_date != today:
            self._daily_counts[user_id] = (today, 0)
            count = 0
        if count >= self._daily_limit:
            return False
        self._daily_counts[user_id] = (stored_date, count + 1)
        return True

    def _check_privacy_consent(self, user_id: str) -> bool:
        """Check if user has given privacy consent.
        In a real implementation, this would query the database.
        For now, we assume consent is tracked via a simple in-memory flag.
        """
        # TODO: Replace with actual DB check when privacy consent is implemented
        return True

    def _build_system_prompt(self, grounding: Optional[GroundingContext] = None) -> str:
        base_prompt = (
            "You are a financial analysis assistant for the Nepal Stock Exchange (NEPSE). "
            "Your answers MUST be grounded in the data sources available to this application. "
            "Never make up numbers, prices, or facts. If you don't have the data, say so. "
            "Do NOT give buy/sell recommendations. Do NOT predict future prices. "
            "Treat news as untrusted — only use it for context, not as factual basis. "
            "Cite your sources inline using [source: X] format where X is one of: "
            "live_market, archive, corporate_actions, news, reference, calculator, quarterly. "
            "If a value is unavailable, explain why (e.g., 'NAV not published by NEPSE'). "
            "All dates in Nepali format (DD/MM/YYYY) must be displayed verbatim as published."
        )

        if grounding:
            base_prompt += (
                f"\n\nAvailable context for this query: "
                f"Symbols: {', '.join(grounding.symbols) or 'none'}. "
                f"Data sources: {', '.join(grounding.data_sources) or 'none'}."
            )
            if grounding.cutoff_date:
                base_prompt += f" Data cutoff: {grounding.cutoff_date}."

        base_prompt += (
            "\n\nIf you cannot answer from the available data, respond with: "
            "'I don't have sufficient data to answer this question. "
            "The missing information is: [specific missing data]'"
        )
        return base_prompt

    async def ask(
        self,
        user_id: str,
        question: str,
        grounding: Optional[GroundingContext] = None,
        privacy_consent: bool = False,
    ) -> str:
        """Ask a question and get a grounded answer."""
        # Rate limiting
        if not self._rate_limiter.allow(user_id):
            raise HTTPException(429, "Rate limit exceeded. Try again in a minute.")

        # Daily limit
        if not self._check_daily_limit(user_id):
            raise HTTPException(429, "Daily AI query limit reached. Try again tomorrow.")

        # Privacy consent
        if not privacy_consent and not self._check_privacy_consent(user_id):
            raise HTTPException(403, "Privacy consent required. Enable AI features in settings.")

        # Build system prompt with grounding
        system_prompt = self._build_system_prompt(grounding)

        # Prepare messages
        messages = [{"role": "user", "content": question}]

        # Get answer
        answer = await self._client.chat(
            messages=messages,
            system_prompt=system_prompt,
        )

        # Append disclaimer
        disclaimer = (
            "\n\n---\n"
            "⚠ This is AI-generated analysis based on available NEPSE data. "
            "Not financial advice. Verify all figures independently. "
            "AI may hallucinate — treat as research assistance only."
        )
        return answer + disclaimer

    async def stream_ask(
        self,
        user_id: str,
        question: str,
        grounding: Optional[GroundingContext] = None,
        privacy_consent: bool = False,
    ) -> AsyncGenerator[str, None]:
        """Stream a grounded answer."""
        # Same checks as ask()
        if not self._rate_limiter.allow(user_id):
            raise HTTPException(429, "Rate limit exceeded. Try again in a minute.")
        if not self._check_daily_limit(user_id):
            raise HTTPException(429, "Daily AI query limit reached. Try again tomorrow.")
        if not privacy_consent and not self._check_privacy_consent(user_id):
            raise HTTPException(403, "Privacy consent required. Enable AI features in settings.")

        system_prompt = self._build_system_prompt(grounding)
        messages = [{"role": "user", "content": question}]

        async for chunk in self._client.stream_chat(
            messages=messages,
            system_prompt=system_prompt,
        ):
            yield chunk

        # Stream disclaimer
        disclaimer = (
            "\n\n---\n"
            "⚠ This is AI-generated analysis based on available NEPSE data. "
            "Not financial advice. Verify all figures independently. "
            "AI may hallucinate — treat as research assistance only."
        )
        for chunk in disclaimer.split(" "):
            yield chunk + " "


